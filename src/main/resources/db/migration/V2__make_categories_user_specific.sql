
-- Remove existing expenses because they reference categories.
DROP TABLE expenses;

-- Recreate categories with user ownership.
DROP TABLE categories;

CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    description VARCHAR(255),
    created_at TIMESTAMP NOT NULL,
    deleted_at TIMESTAMP,
    user_id BIGINT NOT NULL,

    CONSTRAINT fk_categories_user
        FOREIGN KEY (user_id) REFERENCES users(id),

    CONSTRAINT uq_categories_user_name
        UNIQUE (user_id, name)
);

-- Recreate expenses with the original structure.
CREATE TABLE expenses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    amount NUMERIC(12, 2) NOT NULL CHECK (amount >= 0.01),
    description VARCHAR(255),
    expense_date DATE NOT NULL,
    created_at TIMESTAMP NOT NULL,
    updated_at TIMESTAMP,
    deleted_at TIMESTAMP,
    user_id BIGINT NOT NULL,
    category_id BIGINT NOT NULL,

    CONSTRAINT fk_expenses_user
        FOREIGN KEY (user_id) REFERENCES users(id),

    CONSTRAINT fk_expenses_category
        FOREIGN KEY (category_id) REFERENCES categories(id)
);

CREATE INDEX idx_expenses_user_id ON expenses(user_id);
CREATE INDEX idx_expenses_category_id ON expenses(category_id);
CREATE INDEX idx_expenses_expense_date ON expenses(expense_date);

CREATE INDEX idx_expenses_active_user
    ON expenses(user_id, expense_date)
    WHERE deleted_at IS NULL;
